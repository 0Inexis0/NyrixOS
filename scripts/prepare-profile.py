#!/usr/bin/env python3
"""Build a disposable Archiso profile from packaged releng plus our overlay."""
import argparse
from pathlib import Path
import shutil

parser = argparse.ArgumentParser()
parser.add_argument('destination', type=Path)
parser.add_argument('--upstream', type=Path, default=Path('/usr/share/archiso/configs/releng'))
args = parser.parse_args()
repo = Path(__file__).resolve().parents[1]
if args.destination.exists():
    parser.error('destination already exists; use a fresh build directory')
if not (args.upstream / 'profiledef.sh').is_file():
    parser.error('Archiso releng profile missing; install archiso on an Arch build host')
shutil.copytree(args.upstream, args.destination, symlinks=True)
root = args.destination / 'airootfs'
# Remove only inherited generated-profile links, not anything on the build host.
units = root / 'etc/systemd/system'
for entry in list(units.rglob('*')):
    if entry.is_symlink():
        entry.unlink()
for relative in ['etc/systemd/system/getty@tty1.service.d', 'etc/systemd/system/serial-getty@.service.d', 'etc/cloud', 'root']:
    path = root / relative
    if path.is_dir():
        shutil.rmtree(path)
# NetworkManager owns DNS and links; do not keep releng's networkd configuration.
network = root / 'etc/systemd/network'
if network.exists():
    shutil.rmtree(network)
resolv = root / 'etc/resolv.conf'
resolv.unlink(missing_ok=True)
resolv.symlink_to('/run/NetworkManager/resolv.conf')
shutil.copytree(repo / 'iso/overlay', root, dirs_exist_ok=True)
(root / 'etc/skel/.config/hypr').mkdir(parents=True, exist_ok=True)
shutil.copyfile(repo / 'system/config/hyprland.lua', root / 'etc/skel/.config/hypr/hyprland.lua')
shutil.copyfile(repo / 'system/nyrix-session', root / 'usr/local/bin/nyrix-session')
shutil.copytree(repo / 'desktop/config', root / 'etc/skel/.config', dirs_exist_ok=True)
shutil.copytree(repo / 'desktop/bin', root / 'usr/local/bin', dirs_exist_ok=True)
# Public installer payload only; never bundle .git, private infrastructure or build output.
for directory in ['system', 'install', 'desktop']:
    shutil.copytree(repo / directory, root / 'opt/nyrixos' / directory)

(root / 'root').mkdir(mode=0o750, exist_ok=True)
(root / 'etc/passwd').write_text('root:x:0:0:root:/root:/usr/bin/bash\n')
(root / 'etc/shadow').write_text('root:!:14871::::::\n')
(root / 'etc/os-release').write_text('''NAME="NyrixOS"
PRETTY_NAME="NyrixOS 0.1 Development Live"
ID=nyrixos
ID_LIKE=arch
BUILD_ID=development
HOME_URL="https://github.com/0Inexis0/NyrixOS"
''')
for service in ['NetworkManager', 'bluetooth', 'nyrix-live-user', 'qemu-guest-agent', 'systemd-timesyncd', 'pacman-init']:
    wants = units / 'multi-user.target.wants'
    wants.mkdir(parents=True, exist_ok=True)
    prefix = '/etc/systemd/system' if service in ['nyrix-live-user', 'pacman-init'] else '/usr/lib/systemd/system'
    (wants / f'{service}.service').symlink_to(f'{prefix}/{service}.service')
(units / 'default.target').symlink_to('/usr/lib/systemd/system/multi-user.target')
# No network login or cloud metadata provisioning in the distributable live image.
for service in ['sshd.service', 'cloud-init.target']:
    (units / service).symlink_to('/dev/null')
packages = []
for manifest in ['system/packages.x86_64', 'desktop/packages.x86_64', 'iso/packages.x86_64']:
    for line in (repo / manifest).read_text().splitlines():
        package = line.strip()
        if package and not package.startswith('#') and package not in packages:
            packages.append(package)
(args.destination / 'packages.x86_64').write_text('\n'.join(packages) + '\n')
profile = args.destination / 'profiledef.sh'
profile.write_text('''#!/usr/bin/env bash
# Generated by NyrixOS scripts/prepare-profile.py
iso_name="nyrixos"
iso_label="NYRIX_$(date -u +%Y%m)"
iso_publisher="NyrixOS <https://github.com/0Inexis0/NyrixOS>"
iso_application="NyrixOS Arch + Hyprland Live"
iso_version="0.1.$(date -u +%Y%m%d.%H%M)"
install_dir="arch"
bootmodes=('uefi.systemd-boot')
pacman_conf="pacman.conf"
airootfs_image_type="squashfs"
airootfs_image_tool_options=('-comp' 'zstd' '-Xcompression-level' '6' '-processors' '2')
file_permissions=(
  ["/etc/shadow"]="0:0:400"
  ["/root"]="0:0:750"
  ["/etc/sudoers.d/10-nyrix-live"]="0:0:440"
  ["/usr/local/bin/nyrix-session"]="0:0:755"
  ["/usr/local/bin/nyrix-live-user"]="0:0:755"
  ["/usr/local/bin/nyrix-desktop"]="0:0:755"
  ["/usr/local/bin/nyrix-controls"]="0:0:755"
  ["/usr/local/bin/nyrix-radio-status"]="0:0:755"
)
''')
# Every desktop helper must be executable inside the generated image.
with profile.open('a') as stream:
    for helper in sorted((repo / 'desktop/bin').iterdir()):
        stream.write(f'file_permissions["/usr/local/bin/{helper.name}"]="0:0:755"\n')
for bootfile in (args.destination / 'efiboot/loader/entries').glob('*.conf'):
    if bootfile.name != '01-archiso-linux.conf':
        bootfile.unlink()
(args.destination / 'efiboot/loader/loader.conf').write_text('default 01-archiso-linux.conf\ntimeout 3\nconsole-mode keep\n')
for bootfile in (args.destination / 'efiboot').rglob('*'):
    if bootfile.is_file():
        bootfile.write_text(bootfile.read_text().replace('Arch Linux', 'NyrixOS'))
# Git checkout umasks must never make the live desktop unreadable to its user.
for entry in args.destination.rglob('*'):
    if not entry.is_symlink():
        entry.chmod(0o755 if entry.is_dir() else 0o644)
for entry in (root / 'usr/local/bin').iterdir():
    if entry.is_file():
        entry.chmod(0o755)
print(args.destination)
